const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps-script/MarketReportWebSync.gs', 'utf8');
const context = {};
vm.runInNewContext(source, context, {filename:'MarketReportWebSync.gs'});
const validate = context.validateMarketReportEvidenceBeforeSave_;
assert.equal(typeof validate, 'function');
const names = ['金','原油','日経225先物','USD/JPY','EUR/USD','BTCUSD'];
const prices = ['4,020.60ドル/oz（2026-10-27 07:40 JST確認）','101.76ドル/bbl（2026-10-26 NY清算）','62,890円（2026-10-27 06:00 JST確認）','157.50円（2026-10-27 07:45 JST確認）','1.1174（2026-10-27 07:45 JST確認）','79,902.86ドル（2026-10-27 05:39 JST確認）'];
function makeReport() {
 const markets=names.map((name,i)=>({name,price:prices[i],direction:'本文記載',material:'本文記載',outlook:'本文記載',levels:'本文記載',risk:'本文記載'}));
 return {date:'2026-10-27',time:'08:00',title:'マーケットレポート｜2026/10/27（火）08:00',fullText:'主要市場データ\n'+names.map((n,i)=>n+'：'+prices[i]).join('\n'),markets};
}
let report=makeReport();
assert.deepEqual(JSON.parse(JSON.stringify(validate(report))),{ok:true,marketCount:6,bodyLength:report.fullText.length});
assert.equal(report.markets[0].verificationStatus,'verified');
assert.equal(report.markets[1].verificationStatus,'reference');
console.log('PASS six body-grounded markets and verified/reference classification');
report=makeReport(); report.fullText='';
assert.throws(()=>validate(report),/fullText is required/);
console.log('PASS missing fullText rejected');
report=makeReport(); report.markets.pop();
assert.throws(()=>validate(report),/structured market record is missing/);
console.log('PASS missing market rejected');
report=makeReport(); report.markets[0].price='4,021.60ドル/oz（2026-10-27 07:40 JST確認）';
assert.throws(()=>validate(report),/do not occur in fullText/);
console.log('PASS body/structured price mismatch rejected');
report=makeReport(); report.markets[0].price='4,020.60ドル/oz（2026-10-27 08:01 JST確認）'; report.fullText=report.fullText.replace('07:40','08:01');
assert.throws(()=>validate(report),/after the report cutoff/);
console.log('PASS post-cutoff observation rejected');
report=makeReport(); report.markets[0].price='取得不能'; report.markets[0].verificationStatus='reference'; report.fullText+='\n金：取得不能';
assert.throws(()=>validate(report),/unavailable price conflicts with reference/);
console.log('PASS reference/unavailable contradiction rejected');
report=makeReport(); report.markets[0].price='4,020.60ドル/oz';
validate(report); assert.equal(report.markets[0].verificationStatus,'reference');
console.log('PASS untimed numeric price conservatively tagged reference');
report=makeReport(); report.markets[0].price='取得不能（本文に確認値なし）'; report.fullText+='\n金：取得不能（本文に確認値なし）';
validate(report); assert.equal(report.markets[0].verificationStatus,'unavailable');
console.log('PASS body-grounded unavailable status preserved');
